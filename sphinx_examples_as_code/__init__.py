# sphinx-gallery's own node type for a gallery example's Python code, in
# place of a ``literal_block``: one child per pygments token, so that names
# in the code can carry links to their documentation. Its language is spelled
# ``lang``, and its source has to be read back off its children. Code in any
# other language stays an ordinary ``literal_block``.
#
# Matched by tag name rather than by ``isinstance``: sphinx-gallery is not a
# dependency of this extension (gallery support is opt-in via
# ``gallery_downloads``), so the class itself can't be imported here.
_GALLERY_CODE_BLOCK_TAGNAME = 'code_links_block'

# Class on the ``inline`` nodes sphinx-gallery interleaves into the above when
# the block has line numbers turned on. Rendering furniture, not source, so
# they're dropped rather than baked into the generated file.
_GALLERY_LINENOS_CLASS = 'linenos'

# A chunk of generated lines tagged with how it should be spaced relative to
# its neighbors when segments are joined (see ``_join_segments``):
#   'code'      real Python source
#   'text'      a plain comment (prose, a paragraph, ...)
#   'directive' a comment block that must be visually set off with a blank
#               line both before and after it (the title header; a
#               ``# NOTE:``-style admonition block)
Segment = tuple[str, list[str]]

# Replacements for non-ASCII chars
ASCII_REPLACEMENTS = str.maketrans(
    {
        '\u2018': "'",  # LEFT SINGLE QUOTATION MARK
        '\u2019': "'",  # RIGHT SINGLE QUOTATION MARK
        '\u201c': '"',  # LEFT DOUBLE QUOTATION MARK
        '\u201d': '"',  # RIGHT DOUBLE QUOTATION MARK
    }
)


def _has_class(node: nodes.Node, css_class: str) -> bool:
    getter = getattr(node, 'get', None)
    return bool(getter) and css_class in getter('classes', [])


def _is_examples_heading(node: nodes.Node) -> bool:
    """Check whether ``node`` is a heading (rubric or title) named "Examples"."""
    return (
        isinstance(node, (nodes.rubric, nodes.title))
        and node.astext().strip().lower() == 'examples'
    )


def _is_see_also_heading(node: nodes.Node) -> bool:
    r"""Check whether ``node`` is a heading (rubric or title) named "See Also".

    Two written forms: a bare ``.. rubric:: See Also`` (flat sibling), or
    ``See Also\\n--------`` underline text (docutils nests it as a section).
    Both get the same treatment as a ``.. seealso::`` directive.
    """
    return (
        isinstance(node, (nodes.rubric, nodes.title))
        and node.astext().strip().lower() == 'see also'
    )


def _is_see_also_section(node: nodes.Node) -> bool:
    """Check whether ``node`` is a nested section titled "See Also"."""
    return (
        isinstance(node, nodes.section)
        and bool(node.children)
        and _is_see_also_heading(node.children[0])
    )


#: Download format names, as written in ``sphinx_examples_as_code_conf['formats']``.
_FMT_PYTHON = 'python'
_FMT_JUPYTER = 'jupyter'
_FMT_MARIMO = 'marimo'


@dataclass(frozen=True)
class _RenderContext:
    """State threaded through the conversion functions for one output format."""

    app: Sphinx
    docname: str
    fmt: str  # _FMT_PYTHON or _FMT_JUPYTER
    in_footer: bool = False


def _normalized_html_baseurl(app: Sphinx) -> str | None:
    """Sphinx's own ``html_baseurl`` config, normalized for use with ``urljoin``.

    ``None`` if unset or not a usable absolute URL. Adds a missing trailing
    slash.
    """
    base_url = app.config.html_baseurl
    if not base_url:
        return None
    parsed = urlsplit(base_url)
    if parsed.scheme not in ('http', 'https') or not parsed.netloc:
        return None
    return base_url if base_url.endswith('/') else base_url + '/'


def _resolve_link_url(node: nodes.reference, ctx: _RenderContext) -> str | None:
    """Resolve a reference node's target to an absolute URL, if possible.

    Returns ``None`` for an unresolved target or when no base URL is
    configured.
    """
    refuri = node.get('refuri')
    if refuri and urlsplit(refuri).netloc:
        return refuri  # already absolute (an external hyperlink)

    base_url = _normalized_html_baseurl(ctx.app)
    if not base_url:
        return None
    current_page_url = urljoin(base_url, ctx.app.builder.get_target_uri(ctx.docname))

    if refuri:
        return urljoin(current_page_url, refuri)

    refid = node.get('refid')
    if refid:
        return f'{current_page_url}#{refid}'

    return None


def _add_comment(lines: list[str], text: str) -> None:
    """Append ``text`` to ``lines`` as one or more Python comment lines."""
    for line in text.splitlines():
        line_ = line.rstrip().translate(ASCII_REPLACEMENTS)
        lines.append(f'# {line_}' if line_ else '#')


# Doctest/code-block content is preformatted: RST markup (xref roles,
# hyperlinks) written inside a comment there passes through as raw text.
# These clean it up without touching real code.
_STRAY_XREF_RE = re.compile(r':(?:py:)?\w+:`([^`<>]+?)\s*(?:<[^<>]+>)?`')
_STRAY_HYPERLINK_RE = re.compile(r'`([^`<>]+?)\s*(?:<([^`<>]+)>)?`_+')


def _clean_stray_rst_markup(text: str) -> str:
    """Strip unparsed cross-reference/hyperlink RST syntax from a comment line."""
    text = _STRAY_XREF_RE.sub(r'\1', text)
    return _STRAY_HYPERLINK_RE.sub(
        lambda m: f'{m.group(1)} <{m.group(2)}>' if m.group(2) else m.group(1), text
    )


def _clean_code_comment(line: str) -> str:
    """Apply stray-markup cleanup and ASCII replacements to comment lines."""
    if line.lstrip().startswith('#'):
        line = _clean_stray_rst_markup(line)
        line = line.translate(ASCII_REPLACEMENTS)
    return line


def _render_reference(node: nodes.reference, ctx: _RenderContext) -> str:
    """Render a resolved or unresolved cross-reference/hyperlink.

    The target URL, if resolved, is used as a clickable markdown link in
    notebooks (always), and as literal URL text in Python scripts (only within the
    footer -- elsewhere in a script the link is simply omitted).
    """
    display = node.astext()
    is_code = any(isinstance(child, nodes.literal) for child in node.children)
    url = _resolve_link_url(node, ctx)

    if url is None:
        return f'`{display}`' if is_code else display

    if ctx.fmt == _FMT_JUPYTER:
        return f'[`{display}`]({url})' if is_code else f'[{display}]({url})'

    if ctx.in_footer:
        # Inline, not surrounded by newlines -- "text url" in place, not a
        # markdown link.
        return f'{display} {url}'

    return f'`{display}`' if is_code else display


def _render_inline(node: nodes.Node, ctx: _RenderContext) -> str:
    """Render a node's inline content to a plain string.

    References go through ``_render_reference``. Other code-like spans
    (double-backtick literals, an unresolved reference's inner literal) are
    backtick-wrapped; everything else is flattened to plain text.
    """
    if isinstance(node, nodes.reference):
        return _render_reference(node, ctx)
    if isinstance(node, nodes.literal):
        return f'`{node.astext()}`'
    if isinstance(node, (nodes.image, nodes.figure, nodes.raw, nodes.comment)):
        return ''
    if isinstance(node, nodes.Text):
        return str(node)
    if hasattr(node, 'children') and node.children:
        return ''.join(_render_inline(child, ctx) for child in node.children)
    return node.astext()


def _join_segments(segments: list[Segment]) -> list[str]:
    """Flatten segments into lines, applying inter-segment spacing rules.

    - a blank line always follows a ``code`` segment, whatever comes next
    - a ``directive`` segment always gets a blank line both before and
      after it
    - otherwise (e.g. prose directly above a code block, or two prose
      segments back to back), no blank line is forced
    """
    lines: list[str] = []
    prev_kind: str | None = None
    for kind, seg_lines in segments:
        if not seg_lines:
            continue
        need_blank = prev_kind is not None and (
            prev_kind == 'code' or kind == 'directive' or prev_kind == 'directive'
        )
        if need_blank:
            lines.append('')
        lines.extend(seg_lines)
        prev_kind = kind
    return lines


def _convert_doctest_block(node: nodes.doctest_block) -> list[Segment]:
    """Convert a doctest block, stripping ``>>> ``/``... `` prompts.

    Non-prompted, non-blank lines are doctest *output* -- dropped entirely,
    not kept as comments.
    """
    lines: list[str] = []
    has_code = False
    for line in node.astext().splitlines():
        if line.startswith('>>> ') or line == '>>>':
            lines.append(_clean_code_comment(line[4:]))
            has_code = True
        elif line.startswith('... ') or line == '...':
            lines.append(_clean_code_comment(line[4:]))
        elif not line.strip():
            lines.append('')
        # else: doctest output line - dropped
    if not has_code:
        return []
    while lines and not lines[-1].strip():
        lines.pop()
    return [('code', lines)]


def _is_gallery_code_block(node: nodes.Node) -> bool:
    """Check whether ``node`` is the node type sphinx-gallery puts example code in."""
    return getattr(node, 'tagname', None) == _GALLERY_CODE_BLOCK_TAGNAME


def _gallery_code_block_source(node: nodes.Element) -> str:
    """Reassemble the source text sphinx-gallery split across per-token nodes."""
    # One child per pygments token (some wrapped in a reference node), which
    # ``astext()`` joins back together with no separator -- apart from the
    # line-number nodes, which were never part of the source.
    return ''.join(
        child.astext() for child in node.children if not _has_class(child, _GALLERY_LINENOS_CLASS)
    )


def _convert_literal_block(node: nodes.Element) -> list[Segment]:
    """Convert a ``.. code-block::``. Python blocks stay code, others become comments."""
    if _is_gallery_code_block(node):
        language, source = node.get('lang', ''), _gallery_code_block_source(node)
    else:
        language, source = node.get('language', ''), node.astext()
    # Case-insensitive: sphinx-gallery emits ``.. code-block:: Python`` (capitalized).
    if language.lower() in _PYTHON_LANGUAGES:
        lines = [_clean_code_comment(line) for line in source.splitlines()]
        while lines and not lines[-1].strip():
            lines.pop()
        return [('code', lines)] if lines else []
    text = source.strip()
    if not text:
        return []
    comment_lines: list[str] = []
    _add_comment(comment_lines, text)
    # 'directive', not 'text': a non-Python literal block (e.g. an RST
    # ``::``-block illustrating a data format) gets blank lines on both
    # sides, same as any other directive.
    return [('directive', comment_lines)]


#: RST underline character per heading level, for Python script output -- the
#: same sequence Sphinx's own documentation uses for sections, subsections,
#: subsubsections, paragraphs, and sub-paragraphs.
_TITLE_UNDERLINE_CHARS = {1: '=', 2: '-', 3: '~', 4: '^', 5: '"', 6: "'"}

#: Deepest heading level either heading style below can represent.
_MAX_HEADING_LEVEL = 6


def _title_underline_segment(title: str, level: int, fmt: str) -> Segment:
    """Build a heading directive segment for ``title`` at the given level.

    A Python script always uses an RST-style title + underline (e.g. ``# Title`` +
    ``# =====``), one character per level (see ``_TITLE_UNDERLINE_CHARS``);
    a Jupyter notebook always uses ATX ``#`` syntax instead (e.g. ``# ### Title``).
    """
    level = min(level, _MAX_HEADING_LEVEL)
    if fmt == _FMT_JUPYTER:
        return ('directive', [f'# {"#" * level} {title}'])
    underline = _TITLE_UNDERLINE_CHARS[level] * len(title)
    return ('directive', [f'# {title}', f'# {underline}'])


def _heading_level(title: nodes.title) -> int:
    """Compute a title's heading level from its ``nodes.section`` nesting depth.

    Counts the title's own section and each ancestor ``nodes.section``.
    Running this on the file's own header would give level 1; a title
    nested inside that comes out level 2, one nested inside that comes out
    level 3, and so on -- clamped to ``_MAX_HEADING_LEVEL``.
    """
    level = 0
    node: nodes.Node | None = title.parent
    while isinstance(node, nodes.section):
        level += 1
        node = node.parent
    return min(level, _MAX_HEADING_LEVEL)


#: Extra indent for an admonition's content, under its ``# LABEL:`` line --
#: Python scripts only (see ``_convert_admonition``).
_ADMONITION_CONTENT_INDENT = '    '


def _indent_comment_line(line: str) -> str:
    """Indent a ``# text`` comment line's content by ``_ADMONITION_CONTENT_INDENT``.

    A bare ``#``, a blank separator line (``''``), and a raw code line (no
    ``#`` prefix at all) all pass through unchanged.
    """
    if not line.startswith('# '):
        return line
    return f'# {_ADMONITION_CONTENT_INDENT}{line.removeprefix("# ")}'


def _is_raw_code_line(line: str) -> bool:
    """Check whether a rendered Python script line is real code, not a ``#`` comment line."""
    return bool(line) and not line.startswith('#')


def _fill_comment_gaps(lines: list[str]) -> list[str]:
    """Turn a blank separator line into a bare ``#`` unless it borders raw code.

    ``_join_segments`` forces a blank line around some segment boundaries
    (e.g. a paragraph followed by a nested list) meant to visually separate
    unrelated top-level content. Folded into one ``# LABEL:`` comment block
    instead (see ``_indent_label_content``/``_definition_segment``), that
    same blank line needs a ``#`` to still read as part of that one block.
    A blank line bordering a raw code line (left flush and uncommented --
    see ``_convert_node``'s doctest/literal-block handling) stays blank,
    since that boundary really is between code and comment.
    """
    result: list[str] = []
    for i, line in enumerate(lines):
        if line != '':
            result.append(line)
            continue
        before = lines[i - 1] if i > 0 else ''
        after = lines[i + 1] if i + 1 < len(lines) else ''
        result.append(line if _is_raw_code_line(before) or _is_raw_code_line(after) else '#')
    return result


def _indent_label_content(lines: list[str], fmt: str) -> list[str]:
    """Indent every line after the first (a ``# LABEL:`` line) under it.

    Python scripts only.
    """
    if fmt != _FMT_PYTHON or not lines:
        return lines
    label, *rest = _fill_comment_gaps(lines)
    return [label, *(_indent_comment_line(line) for line in rest)]


def _definition_segment(node: nodes.definition, ctx: _RenderContext) -> list[Segment]:
    """Convert a definition list's ``definition`` (its indented body), one level under its term.

    Python scripts only, same as ``_indent_label_content``.
    """
    segments: list[Segment] = []
    for child in node.children:
        segments.extend(_convert_node(child, ctx))
    lines = _join_segments(segments)
    if ctx.fmt == _FMT_PYTHON:
        lines = [_indent_comment_line(line) for line in _fill_comment_gaps(lines)]
    return [('text', lines)] if lines else []


def _list_segment(
    node: nodes.bullet_list | nodes.enumerated_list, ctx: _RenderContext
) -> list[Segment]:
    """Convert a bullet/enumerated list to one ``-``/``N.``-marked line per item.

    A blank line on both sides (``'directive'`` kind). A multi-line item's
    continuation lines get the same indent as an admonition's content.
    """
    ordered = isinstance(node, nodes.enumerated_list)
    lines: list[str] = []
    for index, item in enumerate(node.children, start=1):
        if not isinstance(item, nodes.list_item):
            continue
        item_segments: list[Segment] = []
        for child in item.children:
            item_segments.extend(_convert_node(child, ctx))
        item_lines = _join_segments(item_segments)
        if not item_lines:
            continue
        marker = f'{index}. ' if ordered else '- '
        first, *rest = item_lines
        first = f'# {marker}{first.removeprefix("# ")}' if first.startswith('# ') else first
        lines.append(first)
        lines.extend(_indent_comment_line(line) for line in rest)
    return [('directive', lines)] if lines else []


#: Narrowest a generated table column may be, per format.
_TABLE_MIN_WIDTH = {_FMT_PYTHON: 1, _FMT_JUPYTER: 3}


def _table_cell_text(entry: nodes.entry, ctx: _RenderContext) -> str:
    """Render one cell's content as a single line, list items separated by ``;``."""
    parts: list[str] = []
    for child in entry.children:
        if isinstance(child, (nodes.bullet_list, nodes.enumerated_list)):
            items = (_render_inline(item, ctx).strip() for item in child.children)
            parts.append('; '.join(item for item in items if item))
        else:
            parts.append(_render_inline(child, ctx).strip())
    return ' '.join(part for part in parts if part)


def _table_rows(group: nodes.Element, ctx: _RenderContext) -> list[list[str]]:
    """Render a ``thead``/``tbody``'s rows, padding a column-spanning cell with empties."""
    rows: list[list[str]] = []
    for row in group.children:
        cells: list[str] = []
        for entry in row.children:
            cells.append(_table_cell_text(entry, ctx))
            cells.extend([''] * entry.get('morecols', 0))
        if any(cells):
            rows.append(cells)
    return rows


def _table_grid(node: nodes.table, ctx: _RenderContext) -> tuple[list[list[str]], list[list[str]]]:
    """Split a table into header rows and body rows, dropping any column left empty."""
    head: list[list[str]] = []
    body: list[list[str]] = []
    for tgroup in node.children:
        if not isinstance(tgroup, nodes.tgroup):
            continue
        for group in tgroup.children:
            if isinstance(group, nodes.thead):
                head.extend(_table_rows(group, ctx))
            elif isinstance(group, nodes.tbody):
                body.extend(_table_rows(group, ctx))
    columns = max((len(row) for row in [*head, *body]), default=0)
    for row in [*head, *body]:
        row.extend([''] * (columns - len(row)))
    filled = [index for index in range(columns) if any(row[index] for row in body)]
    if not filled or len(filled) == columns:
        return head, body
    return (
        [[row[index] for index in filled] for row in head],
        [[row[index] for index in filled] for row in body],
    )


def _table_widths(rows: list[list[str]], minimum: int) -> list[int]:
    """Measure each column, never narrower than ``minimum``."""
    return [max(minimum, *map(len, column)) for column in zip(*rows, strict=True)]


def _markdown_table_lines(head: list[list[str]], body: list[list[str]]) -> list[str]:
    """Render rows as a Markdown pipe table, with a blank header row if there is none."""
    head = [[cell.replace('|', r'\|') for cell in row] for row in head]
    body = [[cell.replace('|', r'\|') for cell in row] for row in body]
    widths = _table_widths([*head, *body], _TABLE_MIN_WIDTH[_FMT_JUPYTER])

    def render(cells: list[str]) -> str:
        padded = (cell.ljust(width) for cell, width in zip(cells, widths, strict=True))
        return f'| {" | ".join(padded)} |'

    header, *extra = head or [[''] * len(widths)]
    divider = f'| {" | ".join("-" * width for width in widths)} |'
    return [render(header), divider, *(render(cells) for cells in [*extra, *body])]


def _simple_table_lines(head: list[list[str]], body: list[list[str]]) -> list[str]:
    """Render rows as an RST simple table, bordered above, below and under its header."""
    widths = _table_widths([*head, *body], _TABLE_MIN_WIDTH[_FMT_PYTHON])
    border = '  '.join('=' * width for width in widths)

    def render(cells: list[str]) -> str:
        return '  '.join(
            cell.ljust(width) for cell, width in zip(cells, widths, strict=True)
        ).rstrip()

    lines = [border]
    for rows in (head, body):
        if rows:
            lines.extend(render(cells) for cells in rows)
            lines.append(border)
    return lines


def _table_segment(node: nodes.table, ctx: _RenderContext) -> list[Segment]:
    """Convert a table to an RST simple table in a Python script, a Markdown one in Jupyter.

    Each cell is flattened to a single line, the caption sits above.
    """
    head, body = _table_grid(node, ctx)
    if not head and not body:
        return []
    lines: list[str] = []
    caption = next((child for child in node.children if isinstance(child, nodes.title)), None)
    if caption is not None and (text := _render_inline(caption, ctx).strip()):
        _add_comment(lines, text)
        lines.append('#')
    render = _markdown_table_lines if ctx.fmt == _FMT_JUPYTER else _simple_table_lines
    for line in render(head, body):
        _add_comment(lines, line)
    return [('directive', lines)]


def _convert_admonition(
    node: nodes.Element, label: str, ctx: _RenderContext, *, skip_first_title: bool = False
) -> list[Segment]:
    """Convert an admonition-like container to a ``# LABEL:`` directive segment."""
    inner: list[Segment] = [('text', [f'# {label}:'])]
    for child in node.children:
        if skip_first_title and isinstance(child, nodes.title):
            continue
        inner.extend(_convert_node(child, ctx))
    lines = _indent_label_content(_join_segments(inner), ctx.fmt)
    return [('directive', lines)]


def _convert_node(node: nodes.Node, ctx: _RenderContext) -> list[Segment]:
    """Convert ``node`` into zero or more segments."""
    if any(_has_class(node, css_class) for css_class in _SKIP_SUBTREE_CLASSES):
        return []
    if isinstance(node, _IGNORED_TYPES):
        return []
    if isinstance(node, nodes.doctest_block):
        return _convert_doctest_block(node)
    if isinstance(node, nodes.literal_block) or _is_gallery_code_block(node):
        return _convert_literal_block(node)
    if type(node) in _ADMONITION_LABELS:
        if _is_see_also_type(node):
            # "See Also" content is always dropped -- see _build_segments
            # for the bare-rubric form and _is_see_also_section below for
            # the hand-written-heading form.
            return []
        return _convert_admonition(node, _ADMONITION_LABELS[type(node)], ctx)
    if _is_see_also_section(node):
        # a hand-written "See Also\n--------" heading nests as a full
        # section rather than a flat sibling - dropped the same as any
        # other "See Also" form.
        return []
    if isinstance(node, nodes.admonition):
        # generic ``.. admonition:: Custom Title`` - use its own title as the label
        title_node = node.next_node(nodes.title)
        label = title_node.astext().strip() if title_node is not None else 'NOTE'
        return _convert_admonition(node, label, ctx, skip_first_title=True)
    if isinstance(node, nodes.title):
        # Gallery mode only: a sibling section's own heading (the page's own
        # outer title is filtered out before reaching here -- see
        # _process_gallery_page). Renders as a real Markdown heading in
        # Jupyter, at a level relative to its own section nesting (see
        # _heading_level).
        title_text = _render_inline(node, ctx).strip()
        level = _heading_level(node)
        return [_title_underline_segment(title_text, level, ctx.fmt)] if title_text else []
    if isinstance(node, nodes.definition):
        return _definition_segment(node, ctx)
    if isinstance(node, (nodes.bullet_list, nodes.enumerated_list)):
        return _list_segment(node, ctx)
    if isinstance(node, nodes.table):
        return _table_segment(node, ctx)
    if isinstance(node, (*_CONTAINER_TYPES, nodes.section)):
        # nodes.section (gallery mode only): a sphinx-gallery ``# %%`` cell
        # with its own RST heading is a *sibling* section at the document
        # level, an ordinary child in a gallery page's span. Recursing
        # treats it like any other container: its title hits the
        # ``nodes.title`` case just above, its other children go through
        # the normal per-node conversion.
        segments: list[Segment] = []
        for child in node.children:
            segments.extend(_convert_node(child, ctx))
        return segments

    # Plain text-bearing nodes (paragraphs, etc.) - render inline content,
    # backticking code-like cross-references/literals along the way.
    text = _render_inline(node, ctx).strip()
    if not text:
        return []
    comment_lines: list[str] = []
    _add_comment(comment_lines, text)
    return [('text', comment_lines)]


def _has_real_code(source: str) -> bool:
    """Check whether ``source`` contains at least one executable statement."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return False

    return any(
        not isinstance(stmt, ast.Expr) or not isinstance(stmt.value, ast.Constant)
        for stmt in tree.body
    )


def _span_from(parent: nodes.Element, start: int) -> int:
    """Return the end index (exclusive) of a content span starting at ``start``.

    Extends until the next boundary-type node, or to the end of ``parent``'s
    children. A "See Also" heading/section is not treated as a boundary.
    """
    end = start
    for i in range(start, len(parent.children)):
        child = parent.children[i]
        if _is_see_also_heading(child) or _is_see_also_section(child):
            end = i + 1
            continue
        if isinstance(child, _BOUNDARY_TYPES):
            break
        end = i + 1
    return end


def _is_see_also_type(node: nodes.Node) -> bool:
    """Check whether ``node`` is a "See Also" admonition-type node (e.g. ``.. seealso::``)."""
    return type(node) in _ADMONITION_LABELS and _ADMONITION_LABELS[type(node)] == 'SEE ALSO'


def _examples_spans(doctree: nodes.document) -> list[tuple[nodes.Element, int, int, nodes.Node]]:
    """Find every "Examples" heading's content span.

    Returns a list of ``(parent, start, end, heading)`` tuples.
    """
    spans = []
    for heading in doctree.findall(_is_examples_heading):
        parent = heading.parent
        start = parent.index(heading) + 1
        end = _span_from(parent, start)
        spans.append((parent, start, end, heading))
    return spans


def _desc_id(desc: addnodes.desc) -> str | None:
    """Pull the documented object's id (e.g. ``pkg.mod.func``) off a ``desc`` node."""
    signature = desc.next_node(addnodes.desc_signature)
    if signature is not None and signature.get('ids'):
        return signature['ids'][0]
    return None


def _enclosing_descs(node: nodes.Node) -> Iterator[addnodes.desc]:
    """Yield candidate ``desc`` nodes enclosing ``node``, closest first.

    At each ancestor level: the ancestor itself if it's a ``desc``, then
    the nearest preceding sibling ``desc`` under the same parent (an
    "Examples"/"See Also" section written as a real RST heading, not a
    bare ``.. rubric::``, ends up as a sibling of the object's own
    ``desc`` node rather than nested under it).
    """
    ancestor: nodes.Node | None = node.parent
    while ancestor is not None:
        if isinstance(ancestor, addnodes.desc):
            yield ancestor
        parent = ancestor.parent
        if parent is not None:
            index = parent.index(ancestor)
            for sibling in reversed(parent.children[:index]):
                if isinstance(sibling, addnodes.desc):
                    yield sibling
        ancestor = parent


def _qualified_name_for(node: nodes.Node, docname: str, counter: int) -> str:
    """Best-effort identifier used to name the generated file and its title header."""
    for desc in _enclosing_descs(node):
        desc_id = _desc_id(desc)
        if desc_id is not None:
            return desc_id
    base = Path(docname).name or docname
    return f'{base}-example-{counter}'


def _header_title(qualified_name: str) -> str:
    """Build the file's own header title text, e.g. ``Examples from pyvista.read``."""
    return f'Examples from {qualified_name}'


# A plain divider, not tied to any specific text's length the way a title
# underline is (see _title_underline_segment). Renders as a real <hr> in
# Jupyter once the '# ' prefix is stripped for a markdown cell.
_FOOTER_SEPARATOR = '-' * 70


def _footer_segment(footer: str | None, fmt: str, app: Sphinx, docname: str) -> list[Segment]:
    """Build the footer directive segment, if a footer is configured.

    Empty (0 or 1 elements, not a bare ``Segment | None``) so callers can
    just splat it into a segment list. Starts with ``_FOOTER_SEPARATOR``.

    Parsed as RST, the same as any other prose in this extension: a
    hyperlink written as ```` `text <url>`_ ```` becomes a real clickable
    Markdown link in Jupyter and inline "text url" in a Python script (see
    ``in_footer`` on ``_RenderContext``). Plain text with no RST markup at
    all becomes one comment line per line of text, blank-line-separated
    paragraphs kept apart. Only the *default* footer is one line/link (see
    ``_DEFAULT_FOOTER``).

    Parsed independently of the Sphinx build (plain docutils, not through
    Sphinx's own reader) -- only plain RST hyperlink syntax is supported,
    not Sphinx-specific roles like :func:/:class:.
    """
    if not footer:
        return []
    doctree = publish_doctree(footer, settings_overrides={'report_level': 5})
    ctx = _RenderContext(app=app, docname=docname, fmt=fmt, in_footer=True)
    segments: list[Segment] = []
    for node in doctree.children:
        segments.extend(_convert_node(node, ctx))
    lines = _join_segments(segments)
    return [('directive', [f'# {_FOOTER_SEPARATOR}', *lines])] if lines else []


def _strip_comment_prefix(line: str) -> str:
    """Remove the leading ``# `` (or bare ``#``) from a generated comment line."""
    if line == '#':
        return ''
    return line.removeprefix('# ') if line.startswith('# ') else line.removeprefix('#')


def _segments_to_cells(segments: list[Segment]) -> list[tuple[str, list[str]]]:
    """Group segments into notebook cells: consecutive runs become one cell each.

    A run of ``code`` segments becomes a code cell; a run of ``text``/
    ``directive`` segments becomes a markdown cell (same spacing rules as
    ``_join_segments``, with the ``#`` prefix stripped).
    """
    cells: list[tuple[str, list[str]]] = []
    run: list[Segment] = []
    run_kind: str | None = None

    def _flush() -> None:
        if not run:
            return
        joined = _join_segments(run)
        cells.append(
            (
                run_kind,
                [_strip_comment_prefix(line) for line in joined]
                if run_kind == 'markdown'
                else joined,
            )
        )

    for kind, lines in segments:
        if not lines:
            continue
        cell_kind = 'code' if kind == 'code' else 'markdown'
        if cell_kind != run_kind:
            _flush()
            run, run_kind = [], cell_kind
        run.append((kind, lines))
    _flush()
    return cells


def _cell_source(lines: list[str], kind: str) -> list[str]:
    r"""Format lines the way nbformat expects: each ending in ``\\n`` but the last.

    Markdown cells get a trailing hard line break (two spaces) on each
    non-blank line.
    """
    if not lines:
        return []
    if kind == 'markdown':
        lines = [f'{line}  ' if line else line for line in lines]
    return [f'{line}\n' for line in lines[:-1]] + [lines[-1]]


def _build_notebook(cells: list[tuple[str, list[str]]]) -> dict:
    """Build a minimal, valid nbformat-4.5 notebook dict from grouped cells."""
    nb_cells = []
    for i, (kind, lines) in enumerate(cells):
        cell: dict = {
            'cell_type': kind,
            'metadata': {},
            'source': _cell_source(lines, kind),
            'id': f'cell-{i}',
        }
        if kind == 'code':
            cell['execution_count'] = None
            cell['outputs'] = []
        nb_cells.append(cell)

    return {
        'cells': nb_cells,
        'metadata': {
            'kernelspec': {
                'display_name': 'Python 3',
                'language': 'python',
                'name': 'python3',
            },
            'language_info': {'name': 'python', 'pygments_lexer': 'ipython3'},
        },
        'nbformat': 4,
        'nbformat_minor': 5,
    }


def _download_filename(name: str, extension: str) -> str:
    """Return the file name a download is written under, e.g. ``pyvista_read.py``."""
    safe_name = name.replace('.', '_') if name else 'example'
    return f'{safe_name}.{extension}'


def _write_download_file(app: Sphinx, name: str, extension: str, content: str) -> str:
    """Write generated content directly into the builder's downloads dir.

    Returns the written file's path relative to the downloads directory --
    the value to use as a ``download_reference``'s ``filename``.

    Writes straight to ``<outdir>/_downloads/...`` rather than registering
    through ``env.dlfiles``.
    """
    # 32 hex chars, matching Sphinx's own native _downloads/<digest>/... layout.
    digest = hashlib.sha256(content.encode()).hexdigest()[:32]
    filename = _download_filename(name, extension)
    rel_path = f'{digest}/{filename}'

    out_path = Path(app.outdir) / '_downloads' / digest / filename
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding='utf-8')
    return rel_path


def _write_python_script(app: Sphinx, name: str, source: str) -> str:
    """Write a generated Python script; see ``_write_download_file``."""
    return _write_download_file(app, name, 'py', source)


def _write_jupyter_notebook(app: Sphinx, name: str, notebook: dict) -> str:
    """Write a generated Jupyter notebook; see ``_write_download_file``."""
    return _write_download_file(app, name, 'ipynb', json.dumps(notebook, indent=1))


def _drop_future_imports(source: list[str]) -> list[str]:
    """Remove the lines of every ``from __future__`` import that has its lines to itself."""
    try:
        tree = ast.parse(''.join(source))
    except SyntaxError:
        return source

    def lines(node: ast.stmt) -> set[int]:
        return set(range(node.lineno, node.end_lineno + 1))

    future = [n for n in tree.body if isinstance(n, ast.ImportFrom) and n.module == '__future__']
    shared = set().union(*(lines(n) for n in tree.body if n not in future))
    dropped = set().union(*(lines(n) for n in future)) - shared
    return [line for i, line in enumerate(source, start=1) if i not in dropped]


def _write_marimo_notebook(app: Sphinx, name: str, notebook: dict, header: str = '') -> str:
    """Convert a generated Jupyter notebook with marimo's own converter and write it."""
    from marimo._convert.converters import MarimoConvert

    # A __future__ import inside a marimo cell is a SyntaxError when run as a script.
    cells = [
        {**cell, 'source': _drop_future_imports(cell['source'])}
        if cell['cell_type'] == 'code'
        else cell
        for cell in notebook['cells']
    ]
    source = MarimoConvert.from_ipynb(json.dumps({**notebook, 'cells': cells})).to_py()
    return _write_download_file(app, name, 'marimo.py', header + source)


@functools.cache
def _module_distributions() -> dict[str, list[str]]:
    """Map each importable top-level module to the distribution(s) providing it."""
    return importlib.metadata.packages_distributions()


def _canonical_name(requirement: str) -> str:
    """Return a requirement's normalized name, e.g. ``pyvista`` for ``PyVista[all]>=0.4``."""
    name = re.match(r'[A-Za-z0-9._-]*', requirement.strip()).group()
    return re.sub(r'[-_.]+', '-', name).lower()


def _distribution_for(module: str) -> str | None:
    """Return the one installed distribution providing top-level ``module``, if there is one."""
    dists = sorted(set(_module_distributions().get(module, [])))
    if len(dists) == 1:
        return dists[0]
    if not dists:
        # Editable installs can hide their modules from packages_distributions().
        try:
            return importlib.metadata.distribution(module).name
        except importlib.metadata.PackageNotFoundError:
            pass
    logger.debug(
        'sphinx_examples_as_code: no single distribution provides %r (%s), not listed.',
        module,
        ', '.join(dists) or 'none installed',
    )
    return None


def _imported_distributions(source: str) -> list[str]:
    """Return the third-party distributions whose modules ``source`` imports."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    modules = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            modules.update(alias.name.split('.')[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            modules.add(node.module.split('.')[0])
    modules -= {*sys.stdlib_module_names, '__future__'}
    dists = (_distribution_for(module) for module in sorted(modules))
    return [dist for dist in dists if dist is not None]


def _script_dependencies(source: str, extra: list[str]) -> list[str]:
    """Return ``source``'s imported distributions plus ``extra``, which wins on a name clash."""
    deps = {_canonical_name(dist): dist for dist in _imported_distributions(source)}
    deps.update((_canonical_name(req), req) for req in extra)
    return [deps[key] for key in sorted(deps)]


def _script_metadata_header(deps: list[str], requires_python: str | None, run_line: str) -> str:
    """Build a PEP 723 ``# /// script`` block followed by a one-line run instruction."""
    lines = ['# /// script']
    if requires_python:
        lines.append(f'# requires-python = {json.dumps(requires_python)}')
    if deps:
        lines.append('# dependencies = [')
        lines.extend(f'#     {json.dumps(dep)},' for dep in deps)
        lines.append('# ]')
    else:
        lines.append('# dependencies = []')
    lines.extend(['# ///', f'# {run_line}', ''])
    return '\n'.join(lines) + '\n'


def _jupyter_run_line(deps: list[str], filename: str) -> str:
    """Build the one-line command that opens a generated notebook with its dependencies."""
    with_args = ''.join(f' --with {shlex.quote(dep)}' for dep in deps)
    return f'Open this notebook with: `uvx --from jupyterlab{with_args} jupyter-lab {filename}`'


#: Default download link text per format -- see ``sphinx_examples_as_code_conf['link_labels']``.
_DEFAULT_LINK_LABELS = {
    _FMT_PYTHON: 'Download Python script',
    _FMT_JUPYTER: 'Download Jupyter notebook',
    _FMT_MARIMO: 'Download marimo notebook',
}
#: The fixed order formats are offered in, regardless of how
#: ``sphinx_examples_as_code_conf['formats']`` lists them.
_FORMAT_ORDER = (_FMT_PYTHON, _FMT_JUPYTER, _FMT_MARIMO)


def _make_download_node(entries: list[tuple[str, str]]) -> nodes.paragraph:
    """Build one paragraph holding a download link for each ``(label, rel_path)`` entry."""
    paragraph = nodes.paragraph()
    for i, (label, rel_path) in enumerate(entries):
        if i > 0:
            paragraph += nodes.Text(' | ')
        reference = addnodes.download_reference('', reftarget=rel_path)
        reference['filename'] = rel_path
        reference += nodes.Text(label)
        paragraph += reference
    return paragraph


def _build_segments(nodes_in_span: list[nodes.Node], ctx: _RenderContext) -> list[Segment]:
    """Convert a span's nodes into segments.

    A bare ``.. rubric:: See Also`` heading isn't wrapped in a container the
    way ``.. seealso::`` or a nested section are, so everything after it is
    just as much "See Also" content as the heading itself, with no node of
    its own marking where it ends -- dropping the heading and stopping
    there drops all of it.
    """
    segments: list[Segment] = []
    for node in nodes_in_span:
        if isinstance(node, nodes.rubric) and _is_see_also_heading(node):
            break
        segments.extend(_convert_node(node, ctx))
    return segments


def _build_download_entries(
    app: Sphinx,
    docname: str,
    name: str,
    header_title: str,
    nodes_in_span: list[nodes.Node],
    formats: list[str],
    footer: str | None,
    link_labels: dict[str, str],
    script_metadata: dict | None = None,
) -> list[tuple[str, str]]:
    """Convert a span of nodes into written download files, per ``formats``.

    Returns ``(label, rel_path)`` entries for whichever formats are
    requested -- empty if the span has no real code, or ``formats`` itself
    is empty. Shared by the docstring-Examples path and gallery-page path;
    the only differences between them are how ``nodes_in_span``/``name``
    get built, and what ``header_title`` says (see ``_header_title`` vs.
    ``_process_gallery_page``'s own title handling). Always level 1 -- the
    file's own header is the one heading every generated file has exactly
    one of (see ``_title_underline_segment``).
    """
    python_ctx = _RenderContext(app=app, docname=docname, fmt=_FMT_PYTHON)
    python_segments = _build_segments(nodes_in_span, python_ctx)

    if not any(kind == 'code' for kind, _lines in python_segments):
        return []

    python_header = _title_underline_segment(header_title, 1, _FMT_PYTHON)
    python_segments_full = [
        python_header,
        *python_segments,
        *_footer_segment(footer, _FMT_PYTHON, app, docname),
    ]
    source = '\n'.join(_join_segments(python_segments_full)).rstrip() + '\n'

    if not _has_real_code(source):
        return []

    deps: dict[str, list[str]] = {}
    if script_metadata is not None:
        implied = {_FMT_MARIMO: ['marimo']}
        extra = script_metadata['dependencies']
        deps = {
            fmt: _script_dependencies(source, [*implied.get(fmt, []), *extra.get(fmt, [])])
            for fmt in formats
        }

    def notebook_for(run_line: str | None) -> dict:
        jupyter_ctx = _RenderContext(app=app, docname=docname, fmt=_FMT_JUPYTER)
        jupyter_segments = _build_segments(nodes_in_span, jupyter_ctx)
        jupyter_header = _title_underline_segment(header_title, 1, _FMT_JUPYTER)
        run_segments = [('text', [f'# {run_line}'])] if run_line else []
        # Converted separately from the footer and concatenated, rather
        # than joined into one segment list and converted together --
        # the footer always gets its own dedicated cell this way.
        cells = _segments_to_cells([jupyter_header, *run_segments, *jupyter_segments])
        cells.extend(_segments_to_cells(_footer_segment(footer, _FMT_JUPYTER, app, docname)))
        return _build_notebook(cells)

    def header_for(fmt: str, run_line: str) -> str:
        if not deps:
            return ''
        return _script_metadata_header(deps[fmt], script_metadata['requires_python'], run_line)

    entries = []
    for fmt in _FORMAT_ORDER:
        if fmt not in formats:
            continue
        label = link_labels[fmt]
        if fmt == _FMT_PYTHON:
            filename = _download_filename(name, 'py')
            header = header_for(fmt, f'Run this script with: uv run {filename}')
            rel_path = _write_python_script(app, name, header + source)
        elif fmt == _FMT_JUPYTER:
            filename = _download_filename(name, 'ipynb')
            run_line = _jupyter_run_line(deps[fmt], filename) if deps else None
            rel_path = _write_jupyter_notebook(app, name, notebook_for(run_line))
        else:
            filename = _download_filename(name, 'marimo.py')
            run_line = f'Open this notebook with: uvx marimo edit --sandbox {filename}'
            rel_path = _write_marimo_notebook(
                app, name, notebook_for(None), header_for(fmt, run_line)
            )
        entries.append((label, rel_path))

    return entries


def _process_span(
    app: Sphinx,
    docname: str,
    parent: nodes.Element,
    start: int,
    end: int,
    heading: nodes.Node,
    counter: int,
    position: str,
    formats: list[str],
    footer: str | None,
    link_labels: dict[str, str],
    script_metadata: dict | None = None,
) -> None:
    """Convert one Examples span and insert download link(s) if it has real code."""
    nodes_in_span = list(parent.children[start:end])

    name = _qualified_name_for(heading, docname, counter)
    entries = _build_download_entries(
        app,
        docname,
        name,
        _header_title(name),
        nodes_in_span,
        formats,
        footer,
        link_labels,
        script_metadata,
    )
    if not entries:
        return

    download_node = _make_download_node(entries)
    parent.insert(start if position == 'top' else end, download_node)


# ---------------------------------------------------------------------------
# sphinx-gallery integration (opt-in via sphinx_examples_as_code_conf['gallery_downloads'])
# ---------------------------------------------------------------------------
#
# sphinx-gallery's own generated download links live in the doctree behind a
# handful of CSS classes (see gen_rst.py's DOWNLOAD_LINKS_HEADER and
# friends), matched against here instead of node type.

_GALLERY_NOTE_CLASS = 'sphx-glr-download-link-note'  # "go to the end to download" banner
_GALLERY_FOOTER_CLASS = 'sphx-glr-footer'  # the .py/.ipynb/.zip download links themselves
_GALLERY_TIMING_CLASS = 'sphx-glr-timing'  # "Total running time of the script: ..."
_GALLERY_SIGNATURE_CLASS = 'sphx-glr-signature'  # "Gallery generated by Sphinx-Gallery"

# Removed from the doctree entirely -- sphinx-gallery's own download UI,
# which our own link replaces. Timing/signature are deliberately *not* here:
# they stay on the rendered page (see _SKIP_SUBTREE_CLASSES for why they're
# still kept out of the generated download file).
_GALLERY_REMOVED_CLASSES = (_GALLERY_NOTE_CLASS, _GALLERY_FOOTER_CLASS)


def _strip_gallery_furniture(doctree: nodes.document) -> bool:
    """Remove sphinx-gallery's injected download note/footer, if present.

    Returns whether a download footer was found -- i.e. whether this page
    was actually generated by sphinx-gallery in the first place.
    """
    matches = list(
        doctree.findall(lambda n: any(_has_class(n, cls) for cls in _GALLERY_REMOVED_CLASSES))
    )
    found_footer = any(_has_class(node, _GALLERY_FOOTER_CLASS) for node in matches)
    for node in matches:
        if node.parent is not None:
            node.parent.remove(node)
    return found_footer


def _gallery_body(doctree: nodes.document) -> tuple[nodes.Element, int, int]:
    """Return ``(parent, start, end)`` spanning a gallery page's top-level sections.

    A sphinx-gallery page can have several top-level sections in a row (one
    per ``# %%`` cell with its own RST heading, each a sibling section at
    the document level). This spans all of them: from the first section
    found through the end of the document. Falls back to the document
    itself if there's no section at all.
    """
    first_section = next(doctree.findall(nodes.section), None)
    if first_section is None:
        return doctree, 0, len(doctree.children)
    return doctree, doctree.index(first_section), len(doctree.children)


def _gallery_example_name(docname: str) -> str:
    """Best-effort identifier for a gallery page, used to name its generated file(s)."""
    return Path(docname).name or docname


def _gallery_page_title(section: nodes.section) -> str | None:
    """Extract a gallery page's own title text, if it has one."""
    title_node = next((child for child in section.children if isinstance(child, nodes.title)), None)
    if title_node is None:
        return None
    return title_node.astext().strip() or None


def _process_gallery_page(
    app: Sphinx,
    docname: str,
    doctree: nodes.document,
    position: str,
    formats: list[str],
    footer: str | None,
    link_labels: dict[str, str],
    script_metadata: dict | None = None,
) -> None:
    """Replace a sphinx-gallery page's own download footer with converted downloads.

    A no-op for any page sphinx-gallery didn't generate, detected by the
    absence of its download footer.
    """
    if not _strip_gallery_furniture(doctree):
        return

    parent, start, end = _gallery_body(doctree)
    top_level = list(parent.children[start:end])
    if not top_level:
        return

    # The first top-level node is the page's own outer section (title,
    # intro, ...); its title is dropped (our own header replaces it) and
    # the rest of its children flattened into the span. Any further sibling
    # sections (one per "# %%" cell with its own heading) are kept as
    # sections, titles and all -- see _convert_node's nodes.section case.
    first, rest = top_level[0], top_level[1:]
    if isinstance(first, nodes.section):
        title = _gallery_page_title(first)
        nodes_in_span = [child for child in first.children if not isinstance(child, nodes.title)]
        nodes_in_span.extend(rest)
    else:
        title = None
        nodes_in_span = top_level

    name = _gallery_example_name(docname)
    # Uses the page's own title as the header, rather than "Examples from
    # <docname-derived name>". Falls back to the usual header if the page
    # has no title of its own.
    header_title = title if title else _header_title(name)
    entries = _build_download_entries(
        app,
        docname,
        name,
        header_title,
        nodes_in_span,
        formats,
        footer,
        link_labels,
        script_metadata,
    )
    if not entries:
        return

    download_node = _make_download_node(entries)
    if position == 'top' and isinstance(first, nodes.section):
        # Right after the page's own title -- matching what 'top' means for
        # a docstring Examples section -- not before the whole page/title.
        first.insert(1, download_node)
    else:
        parent.insert(start if position == 'top' else end, download_node)


def _process_doctree(app: Sphinx, doctree: nodes.document, docname: str) -> None:
    """Add a download link to every "Examples" section found on this page."""
    if not getattr(app.builder, 'download_support', False):
        # Only HTML-family builders serve a _downloads/ directory - skip
        # everything else (latex, text, man, epub, ...).
        return

    conf = app.config.sphinx_examples_as_code_conf
    position = conf['link_position']
    formats = conf['formats']
    footer = conf['footer']
    link_labels = conf['link_labels']
    script_metadata = conf if conf['script_metadata'] else None

    if conf['gallery_downloads']:
        _process_gallery_page(
            app, docname, doctree, position, formats, footer, link_labels, script_metadata
        )

    # Process spans per shared parent, last to first.
    spans = _examples_spans(doctree)
    numbered_spans = [(*span, i + 1) for i, span in enumerate(spans)]
    for parent, start, end, heading, counter in sorted(
        numbered_spans, key=lambda s: (id(s[0]), -s[1])
    ):
        _process_span(
            app,
            docname,
            parent,
            start,
            end,
            heading,
            counter,
            position,
            formats,
            footer,
            link_labels,
            script_metadata,
        )


# One line, one link.
_DEFAULT_FOOTER = (
    'Generated by `sphinx-examples-as-code <https://github.com/pyvista/sphinx-examples-as-code>`_'
)

#: Default value for every recognized ``sphinx_examples_as_code_conf`` key --
#: and the only keys it recognizes; anything else is a typo, caught at build
#: start rather than silently doing nothing.
_CONF_DEFAULTS: dict[str, object] = {
    'link_position': 'top',
    'formats': list(_FORMAT_ORDER),
    'gallery_downloads': False,
    'footer': _DEFAULT_FOOTER,
    'link_labels': _DEFAULT_LINK_LABELS,
    'script_metadata': False,
    'dependencies': {},
    'requires_python': None,
}


def _coerce_conf_value(key: str, value: object) -> object:
    """Coerce a value that may have arrived as a raw string; pass anything else through.

    A value set directly in ``conf.py`` already has its real Python type. A
    value set via ``-D sphinx_examples_as_code_conf.key=value`` on the
    command line always arrives as a plain string -- Sphinx's own type
    coercion for ``-D`` overrides (bool ``0``/``1``, comma-split lists, ...)
    only applies to a config value's top level, never to a dict's individual
    keys, so it's redone here for the two keys that need it.
    """
    if not isinstance(value, str):
        return value
    if key == 'formats':
        return value.split(',')
    if key in ('gallery_downloads', 'script_metadata'):
        if value == '0':
            return False
        if value == '1':
            return True
        msg = f"sphinx_examples_as_code_conf[{key!r}] must be '0' or '1', got {value!r}."
        raise ConfigError(msg)
    return value  # link_position, footer, requires_python: a string is already the real type


def _merged_link_labels(value: object) -> dict[str, str]:
    """Merge a user-provided ``link_labels`` override over the defaults.

    A partial override (e.g. just ``{'python': 'Get the script'}``) only changes
    that one format's label; any not given keep their default.
    """
    if not isinstance(value, dict):
        msg = f"sphinx_examples_as_code_conf['link_labels'] must be a dict, got {value!r}."
        raise ConfigError(msg)
    unknown = sorted(set(value) - set(_DEFAULT_LINK_LABELS))
    if unknown:
        valid = ', '.join(sorted(_DEFAULT_LINK_LABELS))
        msg = (
            f"sphinx_examples_as_code_conf['link_labels'] has unknown key(s) {unknown} "
            f'(valid keys: {valid}).'
        )
        raise ConfigError(msg + _renamed_hint(unknown))
    return {**_DEFAULT_LINK_LABELS, **value}


#: Retired format names and the names that replace them.
_RENAMED_FORMATS = {'py': _FMT_PYTHON, 'ipynb': _FMT_JUPYTER}


def _renamed_hint(unknown: list[str]) -> str:
    """Return a `` Renamed: ...`` suffix naming the replacement for any retired format name."""
    renamed = [
        f'{old!r} is now {_RENAMED_FORMATS[old]!r}' for old in unknown if old in _RENAMED_FORMATS
    ]
    return f' Renamed: {", ".join(renamed)}.' if renamed else ''


def _validate_formats(formats: list[str]) -> None:
    """Raise a ``ConfigError`` for any unknown ``formats`` entry."""
    unknown = [fmt for fmt in formats if fmt not in _FORMAT_ORDER]
    if not unknown:
        return
    valid = ', '.join(_FORMAT_ORDER)
    msg = (
        f"sphinx_examples_as_code_conf['formats'] has unknown format(s) {unknown} (valid: {valid})."
    )
    raise ConfigError(msg + _renamed_hint(unknown))


def _validate_dependencies(dependencies: object) -> None:
    """Raise a ``ConfigError`` unless ``dependencies`` maps known formats to lists of strings."""
    key = "sphinx_examples_as_code_conf['dependencies']"
    if not isinstance(dependencies, dict):
        msg = f'{key} must be a dict, got {dependencies!r}.'
        raise ConfigError(msg)
    unknown = sorted(set(dependencies) - set(_FORMAT_ORDER))
    if unknown:
        msg = f'{key} has unknown format(s) {unknown} (valid: {", ".join(_FORMAT_ORDER)}).'
        raise ConfigError(msg + _renamed_hint(unknown))
    for fmt, reqs in dependencies.items():
        if not isinstance(reqs, list) or not all(isinstance(req, str) for req in reqs):
            msg = f'{key}[{fmt!r}] must be a list of strings, got {reqs!r}.'
            raise ConfigError(msg)


def _marimo_converter_available() -> bool:
    """Check whether marimo's notebook converter (marimo 0.14 or newer) is importable."""
    try:
        return importlib.util.find_spec('marimo._convert.converters') is not None
    except ModuleNotFoundError:
        return False


def _finalize_conf(_app: Sphinx, config: Config) -> None:
    """Merge ``sphinx_examples_as_code_conf`` over the defaults, coerce it, and validate it.

    Runs once at ``config-inited``, so every other handler can just read
    ``app.config.sphinx_examples_as_code_conf[key]`` and get a fully-formed,
    correctly-typed dict back -- regardless of whether the user set it
    (fully, partially, or not at all) in ``conf.py``, via ``-D``, or both.
    """
    user_conf = config.sphinx_examples_as_code_conf
    unknown = sorted(set(user_conf) - set(_CONF_DEFAULTS))
    if unknown:
        valid = ', '.join(sorted(_CONF_DEFAULTS))
        msg = f'sphinx_examples_as_code_conf has unknown key(s) {unknown} (valid keys: {valid}).'
        raise ConfigError(msg)

    merged = dict(_CONF_DEFAULTS)
    merged.update((key, _coerce_conf_value(key, value)) for key, value in user_conf.items())
    merged['link_labels'] = _merged_link_labels(merged['link_labels'])
    _validate_dependencies(merged['dependencies'])
    _validate_formats(merged['formats'])
    if _FMT_MARIMO in merged['formats'] and not _marimo_converter_available():
        if 'formats' in user_conf:
            msg = (
                "sphinx_examples_as_code_conf['formats'] includes 'marimo', which needs "
                'marimo 0.14 or newer. Install it with: '
                "pip install 'sphinx-examples-as-code[marimo]'"
            )
            raise ConfigError(msg)
        merged['formats'] = [fmt for fmt in merged['formats'] if fmt != _FMT_MARIMO]
    config.sphinx_examples_as_code_conf = merged


#: sphinx-gallery settings that only shape its own notebook downloads.
_GALLERY_NOTEBOOK_KEYS = (
    'pypandoc',
    'notebook_extensions',
    'first_notebook_cell',
    'last_notebook_cell',
    'notebook_images',
)


def _disable_gallery_notebooks(_app: Sphinx, config: Config) -> None:
    """Turn off sphinx-gallery's notebook output when ``gallery_downloads`` is on."""
    gallery_downloads = config.sphinx_examples_as_code_conf.get('gallery_downloads', False)
    if not _coerce_conf_value('gallery_downloads', gallery_downloads):
        return
    gallery_conf = getattr(config, 'sphinx_gallery_conf', None)
    if not isinstance(gallery_conf, dict):
        return
    from sphinx_gallery.gen_gallery import DEFAULT_GALLERY_CONF

    overrides = {'pypandoc': False, 'notebook_extensions': set()}
    set_keys = [
        key
        for key in _GALLERY_NOTEBOOK_KEYS
        if gallery_conf.get(key, DEFAULT_GALLERY_CONF[key])
        not in (DEFAULT_GALLERY_CONF[key], overrides.get(key))
    ]
    if set_keys:
        logger.warning(
            'sphinx_gallery_conf key(s) %s have no effect: sphinx_examples_as_code writes the '
            "gallery downloads, so sphinx-gallery's own notebooks are not generated.",
            ', '.join(repr(key) for key in set_keys),
            type='sphinx_examples_as_code',
            subtype='gallery_conf',
        )
    config.sphinx_gallery_conf = {**gallery_conf, **overrides}


def setup(app: Sphinx) -> dict:  # numpydoc ignore=RT01
    """Register the extension."""
    app.connect('doctree-resolved', _process_doctree)
    app.connect('config-inited', _finalize_conf)
    # sphinx-gallery fills its own defaults at priority 10.
    app.connect('config-inited', _disable_gallery_notebooks, priority=5)
    app.add_config_value('sphinx_examples_as_code_conf', {}, 'env')

    return {
        'version': __version__,
        'parallel_read_safe': True,
        'parallel_write_safe': True,
    }
